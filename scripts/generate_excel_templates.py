#!/usr/bin/env python3
"""
Fast Zero-Dependency Multi-Sheet XLSX Writer + Generator for:
  1. `update data/update_data.xlsx`
     - Consolidates all 7 source Excel datasets used by the dashboard from `data/`:
       * Sheet 1: `Sale_Revenue_Detail` (only rows >= 407594, i.e. from 01/10/2026 onwards, since rows 2..407593 are locked in frozen cache!)
       * Sheet 2: `Master_Product`
       * Sheet 3: `Inventory_Details`
       * Sheet 4: `Inventory_SKU_Level`
       * Sheet 5: `Inventory_Branch_Level`
       * Sheet 6: `Inventory_Serial_Details`
       * Sheet 7: `Bad_Stock_by_Serial`
       * Sheet 8: `Bao_cao_quan_ly_gia`
  2. `update data/so_sanh_gia.xlsx`
     - Generated by Wall•E (Agent Nén Giá) from the 4 Scouts (TGDĐ, CellphoneS, FPT, Hacom)
     - Includes:
       * Sheet 1: `Thong_Bao_Thay_Doi_Gia` (Price change notifications & time window between 2 updates)
       * Sheet 2: `Ma_Tran_Nen_Gia_PV` (62 matched Phong Vũ SKUs vs 4 competitors)
       * Sheet 3: `Raw_4_Trinh_Sat` (All 150 active priced competitor items from TGDĐ, CellphoneS, FPT, Hacom)
"""

