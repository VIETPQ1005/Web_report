def col_idx_to_letters(idx: int) -> str:
    res = []
    n = idx + 1
    while n > 0:
        n, rem = divmod(n - 1, 26)
        res.append(chr(65 + rem))
    return "".join(reversed(res))


_COL_CACHE = [col_idx_to_letters(i) for i in range(64)]


def _clean_xml_text(s: str) -> str:
    # Strip any illegal XML control chars
    return "".join(ch for ch in s if ch == "\t" or ch == "\n" or ch == "\r" or ord(ch) >= 0x20)


def write_multi_sheet_xlsx(out_path: Path, sheets: list[tuple[str, list[str], list[list]]]):
    """
    Writes a valid OpenXML .xlsx workbook with multiple sheets using sharedStrings.xml.
    sheets: list of (sheet_name, headers, rows)
    """
    out_path.parent.mkdir(parents=True, exist_ok=True)
    shared_map: dict[str, int] = {}
    shared_list: list[str] = []

    def get_si(s: str) -> int:
        idx = shared_map.get(s)
        if idx is None:
            idx = len(shared_list)
            shared_map[s] = idx
            shared_list.append(s)
        return idx

    with zipfile.ZipFile(out_path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        for s_idx, (sname, headers, rows) in enumerate(sheets, start=1):
            lines = [
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
                '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">',
                "<sheetData>",
            ]
            all_rows = [headers] + rows if headers else rows
            for r_num, row in enumerate(all_rows, start=1):
                if not row:
                    continue
                c_parts = []
                for c_idx, val in enumerate(row):
                    if val is None or val == "":
                        continue
                    col_let = _COL_CACHE[c_idx] if c_idx < len(_COL_CACHE) else col_idx_to_letters(c_idx)
                    ref = f"{col_let}{r_num}"
                    if isinstance(val, bool):
                        si = get_si("TRUE" if val else "FALSE")
                        c_parts.append(f'<c r="{ref}" t="s"><v>{si}</v></c>')
                    elif isinstance(val, (int, float)):
                        c_parts.append(f'<c r="{ref}"><v>{val}</v></c>')
                    else:
                        s_val = str(val)
                        # Keep leading-zero codes (SKU, Serial, Site Code) as strings; pure numbers without leading 0 can be numeric if desired
                        si = get_si(_clean_xml_text(s_val))
                        c_parts.append(f'<c r="{ref}" t="s"><v>{si}</v></c>')
                lines.append(f'<row r="{r_num}">{"".join(c_parts)}</row>')
            lines.append("</sheetData></worksheet>")
            zf.writestr(f"xl/worksheets/sheet{s_idx}.xml", "\n".join(lines).encode("utf-8"))

        # sharedStrings.xml
        ss_lines = [
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
            f'<sst xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" count="{len(shared_list)}" uniqueCount="{len(shared_list)}">',
        ]
        for s in shared_list:
            ss_lines.append(f'<si><t xml:space="preserve">{escape(s)}</t></si>')
        ss_lines.append("</sst>")
        zf.writestr("xl/sharedStrings.xml", "\n".join(ss_lines).encode("utf-8"))

        # xl/workbook.xml
        wb_sheets = []
        wb_rels = []
        ct_overrides = []
        for s_idx, (sname, _, _) in enumerate(sheets, start=1):
            safe_name = escape(sname[:31])
            wb_sheets.append(f'<sheet name="{safe_name}" sheetId="{s_idx}" r:id="rId{s_idx}"/>')
            wb_rels.append(
                f'<Relationship Id="rId{s_idx}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet{s_idx}.xml"/>'
            )
            ct_overrides.append(
                f'<Override PartName="/xl/worksheets/sheet{s_idx}.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>'
            )

        ss_rid = len(sheets) + 1
        wb_rels.append(
            f'<Relationship Id="rId{ss_rid}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/sharedStrings" Target="sharedStrings.xml"/>'
        )
        zf.writestr(
            "xl/workbook.xml",
            (
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
                '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" '
                'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">'
                f'<sheets>{"".join(wb_sheets)}</sheets>'
                "</workbook>"
            ).encode("utf-8"),
        )
        zf.writestr(
            "xl/_rels/workbook.xml.rels",
            (
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
                '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                f'{"".join(wb_rels)}'
                "</Relationships>"
            ).encode("utf-8"),
        )
        zf.writestr(
            "_rels/.rels",
            (
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
                '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
                '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>'
                "</Relationships>"
            ).encode("utf-8"),
        )
        zf.writestr(
            "[Content_Types].xml",
            (
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
                '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
                '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
                '<Default Extension="xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'
                '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'
                '<Override PartName="/xl/sharedStrings.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sharedStrings+xml"/>'
                f'{"".join(ct_overrides)}'
                "</Types>"
            ).encode("utf-8"),
        )


def _read_sheet_from_source(fp: Path, min_row: int = 2) -> tuple[list[str], list[list]]:
    headers = []
    rows = []
    if not fp.exists():
        return headers, rows
    for tag, vals in stream_xlsx_rows(fp, min_row=min_row):
        if tag == "__HEADERS__":
            headers = [str(h or "").strip() for h in vals]
        else:
            rows.append(vals)
    return headers, rows


def build_update_data_excel():
    t0 = time.time()
    print("Building `update data/update_data.xlsx` from original source files in `data/`...")
    specs = [
        # Notice: Sale_Revenue_Detail only includes rows from 407594 onwards (from 01/10/2026)!
        ("Sale_Revenue_Detail", DATA_DIR / "Sale_Revenue_Detail.xlsx", FROZEN_SALES_END_ROW + 1),
        ("Master_Product", DATA_DIR / "Master Product.xlsx", 2),
        ("Inventory_Details", DATA_DIR / "Inventory_Details.xlsx", 2),
        ("Inventory_SKU_Level", DATA_DIR / "Inventory_SKU_Level.xlsx", 2),
        ("Inventory_Branch_Level", DATA_DIR / "Inventory_Branch_Level.xlsx", 2),
        ("Inventory_Serial_Details", DATA_DIR / "Inventory Serial Details.xlsx", 2),
        ("Bad_Stock_by_Serial", DATA_DIR / "Bad Stock by Serial.xlsx", 2),
        ("Bao_cao_quan_ly_gia", DATA_DIR / "Bao_cao_quan_ly_gia.xlsx", 2),
    ]
    sheets = []
    for sheet_name, fp, min_r in specs:
        st = time.time()
        hdrs, rws = _read_sheet_from_source(fp, min_row=min_r)
        print(f"  + Sheet `{sheet_name:24s}` <- {fp.name} (min_row={min_r}): {len(rws):,} rows ({time.time() - st:.1f}s)")
        sheets.append((sheet_name, hdrs, rws))

    out_path = UPDATE_DATA_DIR / "update_data.xlsx"
    write_multi_sheet_xlsx(out_path, sheets)
    print(f"Saved `{out_path}` ({out_path.stat().st_size / 1024 / 1024:.2f} MB in {time.time() - t0:.1f}s)")
    return out_path


